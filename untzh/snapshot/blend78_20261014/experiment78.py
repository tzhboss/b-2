def prepare():
    cohort=ex.base.load(core.PRIOR/'cache/cohort.npz')
    scale=ex.base.load('/data/lc/untzh/normalized77_20261014/scale-cache.npz')
    positions=scale['cohort_positions']
    return {'q':torch.as_tensor(cohort['q'],device='cuda'),
            'candidates':torch.as_tensor(cohort['candidates'],device='cuda'),
            'logZ':torch.as_tensor(scale['cohort_logZ'],device='cuda'),
            'legal_newcount':torch.as_tensor(scale['legal_newcount'][positions],device='cuda')}


def prefixes(initial,new,tape):
    E,R,opt=ex.init_model(initial)
    zero={'E':initial['E'],'R':initial['R'],'optimizer':copy.deepcopy(opt.state_dict())}
    # Reuse the real prefix5 generated by076; no repeat warmup needed.
    five=torch.load('/data/lc/untzh/confirm76_20261014/prefix5.pt',map_location='cpu',weights_only=True)
    ten=torch.load(core.PRIOR/'cache/prefix10.pt',map_location='cpu',weights_only=True)
    return {0:zero,5:five,10:ten}


def calibrate(initial,prefix,new,tape,data,start,rho):
    E,R,opt=core.model(initial,prefix);rng=np.random.default_rng(17);rows=collections.defaultdict(list)
    for j in range(start,start+8):
        chosen=rng.choice(ex.SIZE,32,replace=False)
        gl=torch.autograd.grad(ex.base.learning(E,R,new,tape,j),E)[0]
        for signal in ['absolute','mass']:
            gp=torch.autograd.grad(prev.penalties(E,data,chosen,signal),E)[0]
            rows[signal].append([float(gl[ex.N:].double().norm()),float(gp[ex.N:].double().norm())])
    result={}
    for signal,values in rows.items():
        a=np.array(values);result[signal]={'lambda':rho*np.sqrt(np.mean(a[:,0]**2))/np.sqrt(np.mean(a[:,1]**2)),'norms':values}
    return result


def train(name,spec,initial,prefix,new,tape,data,cal):
    started=time.monotonic();epoch0,method,rho=spec;E,R,opt=core.model(initial,prefix)
    rng=np.random.default_rng(17);records=[]
    for j in range(epoch0*37,740):
        chosen=rng.choice(ex.SIZE,32,replace=False)
        loss=ex.base.learning(E,R,new,tape,j);gl=torch.autograd.grad(loss,E)[0]
        bn=float(gl[ex.N:].double().norm());components={};losses={}
        needed=['absolute','mass'] if method in ['blend','absolute_normmatched','mass_normmatched'] else [method]
        for s in needed:
            pen=prev.penalties(E,data,chosen,s);gp=torch.autograd.grad(pen,E)[0]
            pn=float(gp[ex.N:].double().norm());alpha=min(cal[s]['lambda'],rho*bn/pn) if pn else 0.
            components[s]=alpha*gp;losses[s]=float(pen)
        if method=='blend':combined=.5*(components['absolute']+components['mass'])
        elif method.endswith('_normmatched'):
            mixed=.5*(components['absolute']+components['mass'])
            direction=components[method.split('_')[0]]
            mn,dn=float(mixed[ex.N:].double().norm()),float(direction[ex.N:].double().norm())
            combined=direction*(mn/dn) if dn else direction
        else:combined=components[method]
        ratio=float(combined[ex.N:].double().norm())/bn if bn else 0.
        assert ratio<=rho*(1+1e-5)
        opt.zero_grad(set_to_none=True);E.grad=gl+combined;opt.step()
        if not torch.isfinite(loss) or not torch.isfinite(E).all():raise FloatingPointError(name)
        records.append({'step':j,'epoch':int(tape['epochs'][j]),'learning_loss':float(loss),
                        'penalties':losses,'actual_gradient_ratio':ratio})
        if j==739 or tape['epochs'][j+1]!=tape['epochs'][j]:ex.progress('train',arm=name,epoch=int(tape['epochs'][j]),seconds=time.monotonic()-started)
    assert torch.equal(E[:ex.N].detach().cpu(),initial['E'][:ex.N]) and torch.equal(R.cpu(),initial['R'])
    out=ROOT/'models'/name;out.mkdir(parents=True)
    torch.save({'E':E.detach().cpu().double(),'R':R.cpu().double()},out/'epoch-20.pt')
    ex.base.write(out/'steps.json',records)
    result={'seconds':time.monotonic()-started,'spec':spec,'mean_actual_gradient_ratio':float(np.mean([x['actual_gradient_ratio'] for x in records])),
            'max_actual_gradient_ratio':max(x['actual_gradient_ratio'] for x in records),'old_frozen_equal':True}
    ex.base.write(out/'training.json',result);return result


def main():
    torch.set_num_threads(2);torch.manual_seed(17);torch.use_deterministic_algorithms(True)
    torch.backends.cuda.matmul.allow_tf32=False;torch.backends.cudnn.allow_tf32=False
    started=time.monotonic();ex.progress('starting')
    initial=torch.load(ex.SRC/'entity_common_20261011/artifacts/incremental/newentityonly-distmult-s17/initial.pt',map_location='cpu',weights_only=True)
    d=ex.base.load(ex.SRC/'entity_diagnostic42_20261012/artifacts/data/train.npz');old,new=d['old'],d['new']
    tape=ex.base.load(ex.SRC/'matched_protection52_20261013/artifacts/tape/learning.npz')
    tick=time.monotonic();data=prepare();prefix=prefixes(initial,new,tape)
    cal={name:calibrate(initial,prefix[spec[0]],new,tape,data,spec[0]*37,spec[2]) for name,spec in ARMS.items()}
    ex.dump('calibration.json',cal);costs={'prepare_seconds':time.monotonic()-tick,'training':{}}
    for name,spec in ARMS.items():
        costs['training'][name]=train(name,spec,initial,prefix[spec[0]],new,tape,data,cal[name]);ex.dump('costs-running.json',costs)
    _,costs['evaluation']=core.evaluate(old,new,ARMS)
    costs['total_seconds']=time.monotonic()-started;ex.dump('costs.json',costs);ex.progress('complete',seconds=costs['total_seconds'])


if __name__=='__main__':
    try:main()
    except Exception as exc:ex.progress('failed',error=repr(exc));raise
